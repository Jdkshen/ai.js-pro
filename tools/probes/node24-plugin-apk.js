"nodejs";
const assert = require('assert');
(async () => {
  const plugins = require('plugins');
  const pkg = 'org.aijsprobe.nodeplugin';
  assert.strictEqual(plugins.isInstalled(pkg), true);
  const p = await plugins.load(pkg);
  assert.strictEqual(p.add(7, 11), 18);
  assert.strictEqual(p.nativeAdd(13, 17), 30);
  assert.strictEqual(p.text(), 'real plugin resources');
  assert.strictEqual(p.asset().trim(), 'real plugin assets');
  assert.strictEqual(p.pluginPackage(), pkg);
  assert.strictEqual(p.relativeModule(), 'real relative CommonJS module');
  const JavaType = $java.findClass('org.aijsprobe.nodeplugin.FixturePlugin');
  assert.strictEqual(JavaType.class.getName(), 'org.aijsprobe.nodeplugin.FixturePlugin');
  const identity = new java.util.ArrayList();
  identity.add(p.javaObject);
  assert.strictEqual(identity.get(0).__handle, p.javaObject.__handle);
  assert.strictEqual(await p.javaObject.add.invoke(p.javaObject, [23, 29], 'io'), 52);
  const mainThreadId = android.os.Looper.getMainLooper().getThread().getId();
  const currentThread = java.lang.Thread.currentThread.invoke(null, [], 'current');
  assert.notStrictEqual(currentThread.getId(), mainThreadId);
  assert.strictEqual(java.lang.Thread.currentThread.invoke(null, [], 'ui-sync').getId(), mainThreadId);
  assert.strictEqual((await java.lang.Thread.currentThread.invoke(null, [], 'ui')).getId(), mainThreadId);
  assert.notStrictEqual((await java.lang.Thread.currentThread.invoke(null, [], 'io')).getId(), mainThreadId);
  const map = new java.util.LinkedHashMap();
  map.putAll({name: 'real map', nested: {value: 31}});
  assert.strictEqual(map.get('name'), 'real map');
  assert.strictEqual(map.get('nested').get('value'), 31);
  const connection = await p.javaObject.waitForConnection.invoke(p.javaObject, [], 'io');
  const response = await connection.call.invoke(connection, ['sum', {a: 37, b: 41, nested: {tag: 'binder-map'}}, null], 'io');
  assert.strictEqual(response.get('sum'), 78);
  assert.strictEqual(response.get('nested').get('tag'), 'binder-map');
  assert.notStrictEqual(response.get('pid'), android.os.Process.myPid(), 'real remote Binder process');
  await assert.rejects(connection.call.invoke(connection, ['missing-action', {}, null], 'io'), /unknown action/);
  assert.strictEqual(await plugins.unload(pkg), true);
  assert.strictEqual(java.lang.System.getProperty(pkg + '.unloaded'), 'true');
  const again = await plugins.load(pkg);
  assert.strictEqual(again.add(2, 3), 5);
  await plugins.unloadAll();
  await assert.rejects(Promise.resolve().then(() => plugins.load('org.aijsprobe.missing')), /未安装/);
  await assert.rejects(Promise.resolve().then(() => plugins.load('com.android.settings')), /不是 Auto.js SDK 插件/);
  console.log('NODE_PLUGIN_APK_RESULT ' + JSON.stringify({ok: true, java: true, resources: true, assets: true, jni: true, relativeRequire: true, javaIdentity: true, asyncJava: true, threadModes: true, nestedMap: true, binderService: true, remoteExceptions: true, reload: true}));
})().catch(error => {console.error(error.stack || error); process.exitCode = 1;});
